import requests

URL='https://raw.githubusercontent.com/effect082/examone/main/data/exam_data.json'
real_get=requests.get
r=real_get(URL,timeout=60); r.raise_for_status(); exams=r.json()
byid={e['id']:e for e in exams}

def getq(sec,n):
    return next(q for q in byid[sec]['questions'] if int(q.get('qnum') or 0)==n)

def setq(sec,n,question,options,answer=None):
    q=getq(sec,n)
    q['question']=question; q['options']=options
    if answer is not None: q['correct_answer']=str(answer)

